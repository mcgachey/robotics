import { useEffect, useState } from 'react';
import { AppShell, Button, Group, Loader, Select, Tabs, Text, Title, Center } from '@mantine/core';
import { ColorSchemeToggle, LoginForm, errorMessage, get, post, type Lesson, type Me } from '@robotics/common';
import { LessonView } from './LessonView';

export function App() {
  const [me, setMe] = useState<Me | null | undefined>(undefined); // undefined = still checking
  useEffect(() => {
    get<Me>('/api/me').then(setMe, () => setMe(null));
  }, []);

  if (me === undefined) return <Center mih="100vh"><Loader /></Center>;
  if (me === null || me.role !== 'student') {
    return <LoginForm title="Robotics IDE" role="student" onLogin={setMe} />;
  }
  return <Shell me={me} onLogout={() => setMe(null)} />;
}

function Shell({ me, onLogout }: { me: Me; onLogout: () => void }) {
  const [lessons, setLessons] = useState<Lesson[] | null>(null);
  const [lessonId, setLessonId] = useState<string | null>(null);
  const [error, setError] = useState('');

  useEffect(() => {
    get<Lesson[]>('/api/lessons').then(
      (ls) => {
        setLessons(ls);
        setLessonId(ls[0]?.id ?? null); // single entry for now: open it straight away
      },
      (e) => setError(errorMessage(e)),
    );
  }, []);

  const logout = async () => {
    await post('/api/logout').catch(() => {});
    onLogout();
  };

  return (
    <AppShell header={{ height: 52 }} padding={0}>
      <AppShell.Header>
        <Group h="100%" px="md" justify="space-between">
          <Group>
            <Title order={4}>Robotics IDE</Title>
            {lessons && lessons.length > 0 && (
              <Select
                aria-label="Lesson"
                data={lessons.map((l) => ({ value: l.id, label: l.title }))}
                value={lessonId}
                onChange={setLessonId}
                allowDeselect={false}
                w={260}
              />
            )}
          </Group>
          <Group>
            <Text size="sm">{me.name}</Text>
            <Button variant="default" size="xs" onClick={logout}>Log out</Button>
            <ColorSchemeToggle />
          </Group>
        </Group>
      </AppShell.Header>
      <AppShell.Main>
        {error && <Text c="red" p="md">{error}</Text>}
        {lessons && lessons.length === 0 && <Text p="md">No lessons are available yet. Ask your instructor to enable one.</Text>}
        <Tabs defaultValue="code" keepMounted h="calc(100vh - 52px)" style={{ display: 'flex', flexDirection: 'column' }}>
          <Tabs.List px="md">
            <Tabs.Tab value="code">Code</Tabs.Tab>
            <Tabs.Tab value="docs">Documentation</Tabs.Tab>
          </Tabs.List>
          <Tabs.Panel value="code" style={{ flex: 1, minHeight: 0 }}>
            {lessonId && <LessonView key={lessonId} lessonId={lessonId} />}
          </Tabs.Panel>
          <Tabs.Panel value="docs" style={{ flex: 1, minHeight: 0 }}>
            {/* Javadoc for Robot, generated by `make docs` and bundled into the IDE. */}
            <iframe title="Robot documentation" src="/ide/javadoc/robotics/Robot.html"
              style={{ width: '100%', height: '100%', border: 0, background: 'white' }} />
          </Tabs.Panel>
        </Tabs>
      </AppShell.Main>
    </AppShell>
  );
}
